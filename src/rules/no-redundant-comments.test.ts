import { runRuleTests } from "../testing/run-rule-tests.ts";
import rule from "./no-redundant-comments.ts";

runRuleTests("no-redundant-comments", rule, {
  valid: [
    { name: "a legal header (CMT-02)", code: "/**\n * Copyright (c) 2024 Acme Corp. All rights reserved.\n * Licensed under the Apache License, Version 2.0.\n */\nexport const copyright = 1;" },
    { name: "a regular-expression explanation (CMT-02)", code: "/** Matches an ISO date such as 2024-01-31: four digits, a dash, two digits, a dash, two digits. */\nconst isoDate = /^\\d{4}-\\d{2}-\\d{2}$/;" },
    { name: "a \"why\" comment (CMT-02)", code: "/** Retries once, because the proxy drops the first request after a deploy. */\nexport function sendWithRetry() {}" },
    { name: "the book's clutter has a word outside the name, so it is missed on purpose", code: "class C {\n  /** The processor delay for this component */\n  private backgroundProcessorDelay = -1;\n}" },
    { name: "a doc comment with a block tag", code: "class C {\n  /**\n   * The name.\n   * @internal\n   */\n  name = '';\n}" },
    { name: "a doc comment with an inline tag", code: "/** Returns the {@link Day} of the month. */\nexport function getDayOfMonth() {}" },
    { name: "a plain block comment is not a doc comment", code: "/* Returns the day of the month. */\nexport function getDayOfMonth() {}" },
    { name: "a line comment is not a doc comment", code: "// Returns the day of the month.\nexport function getDayOfMonth() {}" },
    { name: "a doc comment that adds information", code: "/** Returns the day of the month, from 1 to 31. */\nexport function getDayOfMonth() {}" },
    { name: "a doc comment with no content words", code: "/** The */\nexport function getDayOfMonth() {}" },
    { name: "a doc comment not on a declaration", code: "run();\n/** Returns the day. */\nrun();" },
    { name: "a @param with a {type} is never deleted", filename: "file.js", code: "/**\n * Sets the title of the window.\n * @param {string} title The title\n */\nexport function setTitle(title) {}" },
    { name: "a @param that adds information", code: "/**\n * Sets the title of the window.\n * @param title the text shown in the window bar\n */\nexport function setTitle(title: string) {}" },
    { name: "an optional @param with a default", code: "/**\n * Sets the title of the window.\n * @param [title=Untitled] The title\n */\nexport function setTitle(title = 'Untitled') {}" },
    { name: "a directive doc comment is never changed", code: "/** @license MIT */\nexport const license = 1;" },
    { name: "directive comments are left alone", code: "// eslint-disable-next-line no-console\nconsole.log(1);\n/** @jsx h */\nexport const h = 1;" },
  ],
  invalid: [
    {
      name: "the book's `getDayOfMonth`",
      code: "class Day {\n  /** Returns the day of the month. */\n  getDayOfMonth() { return 31; }\n}",
      output: "class Day {\n  getDayOfMonth() { return 31; }\n}",
      errors: [{ messageId: "restatesName", data: { name: "getDayOfMonth" } }],
      behaviour: "new Day().getDayOfMonth()",
    },
    {
      name: "the book's default constructor",
      code: "class AnnualDateRule {\n  /**\n   * Default constructor.\n   */\n  constructor() { this.day = 1; }\n}",
      output: "class AnnualDateRule {\n  constructor() { this.day = 1; }\n}",
      errors: [{ messageId: "restatesName" }],
      filename: "file.js",
      behaviour: "new AnnualDateRule().day",
    },
    {
      name: "an exported function",
      code: "/** Gets the user name */\nexport function getUserName() { return 'ada'; }",
      output: "export function getUserName() { return 'ada'; }",
      errors: 1,
      behaviour: "getUserName()",
    },
    {
      name: "a constant",
      code: "/** The max retries. */\nexport const MAX_RETRIES = 3;",
      output: "export const MAX_RETRIES = 3;",
      errors: 1,
      behaviour: "MAX_RETRIES",
    },
    {
      name: "an interface member",
      code: "interface User {\n  /** The user id. */\n  userId: string;\n}\nexport const user: User = { userId: 'u1' };",
      output: "interface User {\n  userId: string;\n}\nexport const user: User = { userId: 'u1' };",
      errors: 1,
      behaviour: "user",
    },
    {
      name: "an enum member (an enum does not run with types stripped, so no behaviour check)",
      code: "enum Color {\n  /** Red. */\n  Red = 1,\n}",
      output: "enum Color {\n  Red = 1,\n}",
      errors: 1,
    },
    {
      name: "a class property and a method in an object literal",
      code: "class C {\n  /** The count. */\n  count = 2;\n}\nconst o = {\n  /** Gets the size. */\n  getSize() { return 3; },\n};",
      output: "class C {\n  count = 2;\n}\nconst o = {\n  getSize() { return 3; },\n};",
      errors: 2,
      behaviour: "[new C().count, o.getSize()]",
    },
    {
      name: "mandated @param tags (CMT-04), as in the book's `addCD`",
      code: "/**\n * Adds a CD to the shelf in the store.\n * @param title The title\n * @param author The author\n * @param tracks the number of tracks on the CD\n */\nexport function addCd(title: string, author: string, tracks: number) { return [title, author, tracks]; }",
      output: "/**\n * Adds a CD to the shelf in the store.\n * @param tracks the number of tracks on the CD\n */\nexport function addCd(title: string, author: string, tracks: number) { return [title, author, tracks]; }",
      errors: [{ messageId: "restatesParam", data: { name: "title" } }, { messageId: "restatesParam", data: { name: "author" } }],
      behaviour: "addCd('a', 'b', 3)",
    },
    {
      name: "a @param with an empty description, and the blank line it leaves",
      code: "/**\n * Sets the title of the window.\n *\n * @param title\n */\nexport function setTitle(title: string) { return title; }",
      output: "/**\n * Sets the title of the window.\n */\nexport function setTitle(title: string) { return title; }",
      errors: [{ messageId: "restatesParam" }],
      behaviour: "setTitle('x')",
    },
    {
      name: "a @param split into words, with a hyphen",
      code: "/**\n * Greets someone at the door.\n * @param firstName - The first name.\n */\nexport function greet(firstName: string) { return firstName; }",
      output: "/**\n * Greets someone at the door.\n */\nexport function greet(firstName: string) { return firstName; }",
      errors: 1,
      behaviour: "greet('ada')",
    },
    {
      name: "a doc comment that is only redundant @params goes as a whole",
      code: "/** @param title The title */\nexport function show(title: string) { return title; }",
      output: "export function show(title: string) { return title; }",
      errors: 1,
      behaviour: "show('t')",
    },
    {
      name: "when the @params go, a description that restates the name goes too",
      code: "/**\n * Sets the title.\n * @param title The title.\n */\nexport function setTitle(title: string) { return title; }",
      output: "export function setTitle(title: string) { return title; }",
      errors: 1,
      behaviour: "setTitle('t')",
    },
    {
      name: "a redundant doc comment with code on both sides keeps a space",
      code: "const a = 1;/** The b. */const b = a + 1;",
      output: "const a = 1; const b = a + 1;",
      errors: 1,
      behaviour: "[a, b]",
    },
    {
      name: "a redundant doc comment across lines with code on both sides becomes a line break",
      code: "const a = 1; /** The\n b. */ const b = a + 1;",
      output: "const a = 1; \n const b = a + 1;",
      errors: 1,
      behaviour: "[a, b]",
    },
  ],
});
