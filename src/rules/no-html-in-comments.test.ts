import { runRuleTests } from "../testing/run-rule-tests.ts";
import rule from "./no-html-in-comments.ts";

runRuleTests("no-html-in-comments", rule, {
  valid: [
    { name: "a legal header (CMT-02)", code: "/*\n * Copyright (c) 2024 Acme Corp. All rights reserved.\n * Licensed under the Apache License, Version 2.0.\n */\nexport const a = 1;" },
    { name: "a regular-expression explanation (CMT-02)", code: "// Matches a tag name such as `div`: a letter, then letters or digits.\nconst tag = /^[a-z][a-z0-9]*$/;" },
    { name: "a \"why\" comment (CMT-02)", code: "// We retry once because the first request after a deploy is dropped by the proxy.\nretry(send);" },
    { name: "a JSX example in a doc comment", code: "/**\n * Renders a button: <Button onClick={go}>Go</Button>\n */\nexport function Button() {}" },
    { name: "type parameters are not tags", code: "// Map<K, V> and Pair<A, B> and List<I> and Box<P>\nrun();" },
    { name: "comparisons are not tags", code: "// when a < b and b > c\nrun();" },
    { name: "HTML inside an @example section", code: "/**\n * Renders the list.\n * @example\n * render('<ul><li>a</li></ul>');\n */\nexport function render() {}" },
    { name: "HTML inside a fenced code block", code: "/**\n * Output:\n * ```html\n * <p>Hello &amp; welcome</p>\n * ```\n */\nexport function greet() {}" },
    { name: "HTML inside a backtick span", code: "// Wraps the text in `<b>` and escapes `&lt;`.\nrun();" },
    { name: "an ampersand that is not an entity", code: "// Tom & Jerry, R&D, a&&b\nrun();" },
    { name: "a directive comment is never changed", code: "/*! <b>Library</b> v1 @license MIT */\nrun();" },
    { name: "directive comments are left alone", code: "// eslint-disable-next-line no-console\nconsole.log(1);" },
  ],
  invalid: [
    {
      name: "the book's Javadoc with <p>, <pre> and entities",
      code: [
        "/**",
        " * Task to run fit tests.",
        " * This task runs fitnesse tests and publishes the results.",
        " * <p/>",
        " * <pre>",
        " * Usage:",
        " * &lt;taskdef name=&quot;execute-fitnesse-tests&quot;",
        " * </pre>",
        " */",
        "export function task() { return 1; }",
      ].join("\n"),
      output: [
        "/**",
        " * Task to run fit tests.",
        " * This task runs fitnesse tests and publishes the results.",
        " *",
        " *",
        " * Usage:",
        " * <taskdef name=\"execute-fitnesse-tests\"",
        " *",
        " */",
        "export function task() { return 1; }",
      ].join("\n"),
      errors: [{ messageId: "html", data: { html: "<p/>" } }],
      behaviour: "task()",
    },
    {
      name: "inline tags go and keep the text between them",
      code: "// Returns the <b>first</b> <em>visible</em> item.\nexport const first = 1;",
      output: "// Returns the first visible item.\nexport const first = 1;",
      errors: 1,
      behaviour: "first",
    },
    {
      name: "a block tag between two words leaves a space",
      code: "/* one<br>two */\nexport const b = 2;",
      output: "/* one two */\nexport const b = 2;",
      errors: 1,
      behaviour: "b",
    },
    {
      name: "a tag with attributes",
      code: "// <code class=\"x\">run()</code> starts it\nexport const c = 3;",
      output: "// run() starts it\nexport const c = 3;",
      errors: 1,
      behaviour: "c",
    },
    {
      name: "every entity is decoded",
      code: "// a &lt; b &amp;&amp; c &gt; d, &quot;x&quot;, &#39;y&#39;,&nbsp;z\nexport const d = 4;",
      output: "// a < b && c > d, \"x\", 'y', z\nexport const d = 4;",
      errors: 1,
      behaviour: "d",
    },
    {
      name: "a double-escaped entity is reported without a fix",
      code: "// write &amp;lt; for <\nexport const e = 5;",
      output: null,
      errors: 1,
    },
    {
      name: "an escaped tag is reported without a fix, since decoding it makes a tag",
      code: "// wrap it in &lt;b&gt;\nexport const e = 6;",
      output: null,
      errors: 1,
    },
    {
      name: "a comment that is only tags goes as a whole",
      code: "let r = 0\n// <p></p>\n;[1, 2].forEach((v) => { r += v })",
      output: "let r = 0\n;[1, 2].forEach((v) => { r += v })",
      errors: 1,
      behaviour: "r",
    },
    {
      name: "a comment of only tags between `return` and its value, across lines, becomes a line break",
      code: "function f() {\n  return /* <ul>\n  </ul> */ 42\n}",
      output: "function f() {\n  return \n 42\n}",
      errors: 1,
      behaviour: ["f()", "typeof f()"],
    },
    {
      name: "`return/*<br>*/value` keeps a space",
      code: "function f(value) { return/*<br>*/value }",
      output: "function f(value) { return value }",
      errors: 1,
      behaviour: "[1, 'a'].map((v) => f(v))",
    },
  ],
});
