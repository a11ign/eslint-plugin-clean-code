import { runRuleTests } from "../testing/run-rule-tests.ts";
import rule from "./no-commented-out-code.ts";

runRuleTests("no-commented-out-code", rule, {
  valid: [
    { name: "review: an `e.g.` example is prose", code: "export const b = 2; // e.g. parse(\"a=b;c=d\")" },
    { name: "review: an `i.e.`, `eg:`, `ex:`, `example:` and `usage:` comment is prose", code: "// i.e. run();\nrun();\n/* eg: run(); */\nrun();\n// Ex: run();\nrun();\n/* example: run(); */\nrun();\n// USAGE: run();\nrun();" },
    { name: "review: a JetBrains language injection is a directive", code: "// language=SQL\nexport const d = 'select 1';" },
    { name: "review: a JetBrains noinspection is a directive", code: "// noinspection JSUnusedGlobalSymbols\nexport const m = 12;" },
    { name: "review: a comparison states a fact, it is not code", code: "// sum(1, 2) === 3\nexport const n = 13;" },
    { name: "a legal header (CMT-02)", code: "/*\n * Copyright (c) 2024 Acme Corp. All rights reserved.\n * Licensed under the Apache License, Version 2.0.\n */\nexport const a = 1;" },
    { name: "a regular-expression explanation (CMT-02)", code: "// Matches a date such as 2024-01-31: four digits, a dash, two digits, a dash, two digits.\nconst date = /^\\d{4}-\\d{2}-\\d{2}$/;" },
    { name: "a \"why\" comment (CMT-02)", code: "// We retry once because the first request after a deploy is dropped by the proxy.\nretry(send);" },
    { name: "a label starts prose, even when a call follows", code: "// Note: call(x) before anything else.\nrun();" },
    { name: "a URL reads as a label", code: "// https://example.com/docs?page=1\nrun();" },
    { name: "a single word is not code", code: "// deprecated\nrun();" },
    { name: "a parenthesised aside is not code", code: "// (optional)\nrun();" },
    { name: "a list of words is not code", code: "// red, green, blue\nrun();" },
    { name: "a doc comment is not checked", code: "/** foo(); */\nfunction f() {}" },
    { name: "an @example block is not checked", code: "/*\n * @example\n * foo();\n */\nfunction foo() {}" },
    { name: "a TODO is left to no-warning-comments", code: "// TODO(bob)\nrun();" },
    { name: "a FIXME is left to no-warning-comments", code: "// fixme = later;\nrun();" },
    { name: "directive: eslint-disable-next-line", code: "// eslint-disable-next-line no-console\nconsole.log(1);" },
    { name: "directive: eslint-disable with a rule list", code: "/* eslint-disable no-console, no-alert */\nconsole.log(1);" },
    { name: "directive: @ts-expect-error", code: "// @ts-expect-error: wrong on purpose\nconst x: number = 'a';" },
    { name: "directive: #__PURE__", code: "const x = /* #__PURE__ */ make();" },
    { name: "directive: global", code: "/* global foo, bar */\nfoo();" },
    { name: "directive: webpack magic comment", code: "import(/* webpackChunkName: \"x\" */ './x.js');" },
    { name: "directive: a preserved `/*!` comment, though its text parses as a call", code: "/*! keep(this); */\nrun();" },
    { name: "directive: prettier-ignore", code: "// prettier-ignore\nconst m = [1,0,0,1];" },
    { name: "TypeScript-only syntax in a comment is not parsed as JavaScript", code: "// const x: number\nrun();" },
  ],
  invalid: [
    {
      name: "a commented-out call",
      code: "let r = 0;\n// r = 5;\nr += 1;",
      output: "let r = 0;\nr += 1;",
      errors: [{ messageId: "commentedOutCode", line: 2 }],
      behaviour: "r",
    },
    {
      name: "regression: a `;[1, 2]` line after a commented-out line, in code without semicolons, keeps its `;`",
      code: "let r = 0\n// r = 5\n;[1, 2].forEach((x) => { r += x })",
      output: "let r = 0\n;[1, 2].forEach((x) => { r += x })",
      errors: 1,
      behaviour: "r",
    },
    {
      name: "regression: a `;(` line after a commented-out call",
      code: "let r = 1\n// log(r)\n;(() => { r *= 3 })()",
      output: "let r = 1\n;(() => { r *= 3 })()",
      errors: 1,
      behaviour: "r",
    },
    {
      name: "a run of commented-out lines is one report and goes as a whole",
      code: "function f(x) {\n  // if (x > 1) {\n  //   return 2;\n  // }\n  return x;\n}",
      output: "function f(x) {\n  return x;\n}",
      errors: [{ messageId: "commentedOutCode", line: 2, endLine: 4 }],
      behaviour: "[0, 1, 2, -1].map((v) => f(v))",
    },
    {
      name: "a commented-out block with `*` decoration",
      code: "const a = 1;\n/*\n * const a = 2;\n * use(a);\n */\nconst b = a + 1;",
      output: "const a = 1;\nconst b = a + 1;",
      errors: 1,
      behaviour: "[a, b]",
    },
    {
      name: "a commented-out function",
      code: "function f(x) { return x * 2; }\n/*\nfunction f(x) {\n  return x * 3;\n}\n*/\n",
      output: "function f(x) { return x * 2; }\n",
      errors: 1,
      behaviour: "[0, 1, -2].map((v) => f(v))",
    },
    {
      name: "a block comment with a line break between `return` and its value becomes a line break",
      code: "function f() {\n  return /* g();\n  h(); */ 42\n}",
      output: "function f() {\n  return \n 42\n}",
      errors: 1,
      behaviour: ["f()", "typeof f()"],
    },
    {
      name: "`return/*g()*/value` keeps a space",
      code: "function f(value) { return/*g()*/value }",
      output: "function f(value) { return value }",
      errors: 1,
      behaviour: "[1, 'a', null].map((v) => f(v))",
    },
    {
      name: "a trailing commented-out call goes with the space before it",
      code: "let r = 1; // r = 2;\nr += 1;",
      output: "let r = 1;\nr += 1;",
      errors: 1,
      behaviour: "r",
    },
    {
      name: "a commented-out `return` (a function body)",
      code: "function f(x) {\n  // return x + 1;\n  return x - 1;\n}",
      output: "function f(x) {\n  return x - 1;\n}",
      errors: 1,
      behaviour: "[0, 5].map((v) => f(v))",
    },
    {
      name: "a commented-out import",
      code: "// import { a } from './a.js';\nexport const b = 1;",
      output: "export const b = 1;",
      errors: 1,
      behaviour: "b",
    },
    {
      name: "commented-out JSX with an expression container",
      filename: "file.jsx",
      code: "const el = null;\n// <Button onClick={go} />\nexport default el;",
      output: "const el = null;\nexport default el;",
      errors: 1,
      behaviour: "el",
    },
    {
      name: "a TODO line ends the run; the code after it is reported alone",
      code: "let r = 0\n// TODO(bob)\n// r = 5\n;[1].forEach(() => { r++ })",
      output: "let r = 0\n// TODO(bob)\n;[1].forEach(() => { r++ })",
      errors: [{ messageId: "commentedOutCode", line: 3 }],
      behaviour: "r",
    },
    {
      name: "a directive line ends the run and stays",
      code: "let r = 0;\n// eslint-disable-next-line no-plusplus\n// r++;\nr += 2;",
      output: "let r = 0;\n// eslint-disable-next-line no-plusplus\nr += 2;",
      errors: [{ messageId: "commentedOutCode", line: 3 }],
      behaviour: "r",
    },
    {
      name: "CRLF line breaks",
      code: "let r = 0;\r\n// r = 5;\r\n// r++;\r\nr += 1;\r\n",
      output: "let r = 0;\r\nr += 1;\r\n",
      errors: 1,
      behaviour: "r",
    },
  ],
});
